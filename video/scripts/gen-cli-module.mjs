/**
 * Embeds the recorded CLI output into a TS module so the render is
 * deterministic (no fetch/delayRender). The recording itself is the source
 * of truth — re-run scripts/record-cli.sh to refresh both files.
 */
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';

const root = resolve(import.meta.dirname, '..');
const raw = readFileSync(
  resolve(root, 'public/captures/cli-search.ansi.txt'),
  'utf8',
);
mkdirSync(resolve(root, 'src/generated'), {recursive: true});
writeFileSync(
  resolve(root, 'src/generated/cliOutput.ts'),
  '// AUTO-GENERATED by scripts/gen-cli-module.mjs from public/captures/cli-search.ansi.txt\n' +
    '// Real output of `bun cli/src/cli.ts search hero` against the live API — do not edit.\n' +
    `export const CLI_ANSI: string = ${JSON.stringify(raw)};\n`,
);
console.log('wrote src/generated/cliOutput.ts');
